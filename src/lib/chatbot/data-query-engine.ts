// ==================== RESULT FORMATTING ====================

/**
 * Use LLM to format query results into natural language.
 */
async function formatResults(
  query: string,
  spec: QuerySpec,
  data: unknown,
  modelMeta: ModelMeta
): Promise<{ content: string; tokensUsed: number }> {
  const client = getOpenAI();

  // For simple counts, no need for LLM
  if (spec.operation === "count" && typeof data === "number") {
    const filterDesc = Object.entries(spec.filters || {})
      .map(([k, v]) => `${k}: ${v}`)
      .join(", ");
    const content = filterDesc
      ? `There are **${data}** ${modelMeta.displayName.toLowerCase()}(s) matching your criteria (${filterDesc}).`
      : `There are **${data}** ${modelMeta.displayName.toLowerCase()}(s) in total.`;
    return { content, tokensUsed: 0 };
  }

  // For complex results, use LLM to format
  const dataStr = JSON.stringify(data, null, 2).substring(0, 3000);

  const response = await client.chat.completions.create({
    model: DATA_QUERY_MODEL,
    messages: [
      {
        role: "system",
        content: `You are a GRC application assistant. Format the following data query result into a clear, concise natural language response. Use bullet points or tables where appropriate. Keep it under 200 words. Do NOT reveal table names, column names, or technical details. Use friendly, business-oriented language.`,
      },
      {
        role: "user",
        content: `User asked: "${query}"\n\nQuery type: ${spec.operation} on ${modelMeta.displayName}\nResults:\n${dataStr}\n\nFormat this into a helpful response:`,
      },
    ],
    max_completion_tokens: 500,
    temperature: 0.3,
  });

  const content = response.choices[0]?.message?.content || "Here are the results of your query.";
  const tokensUsed = response.usage?.total_tokens || 0;

  return { content, tokensUsed };
}

// ==================== PUBLIC API ====================

/**
 * Process a data query end-to-end:
 * 1. LLM generates structured QuerySpec from natural language
 * 2. Validate the spec against whitelisted schema
 * 3. Execute via Prisma with tenant isolation
 * 4. Format results into natural language
 */
export async function processDataQuery(
  query: string,
  customerAccountId: string,
  userRoles: string[],
  conversationHistory: ConversationMessage[] = [],
  session?: ChatSession
): Promise<DataQueryResult> {
  // Step 1: Generate query spec from natural language (with conversation context)
  const { spec, tokensUsed: specTokens } = await generateQuerySpec(query, userRoles, conversationHistory);

  // Step 2: Validate the spec
  const validation = validateQuerySpec(spec, userRoles);
  if (!validation.valid || !validation.modelMeta) {
    return {
      content: validation.error || "I couldn't understand that data query. Could you rephrase it?",
      confidence: "low",
      tokensUsed: specTokens,
    };
  }

  // Step 3: Execute the query
  let data: unknown;
  try {
    data = await executeQuery(spec, validation.modelMeta, customerAccountId, session);
  } catch (error) {
    console.error("[DataQuery] Execution error:", error);
    console.error("[DataQuery] Failed spec:", JSON.stringify(spec, null, 2));
    return {
      content: "I encountered an error while fetching the data. Please try rephrasing your question or contact the administrator.",
      confidence: "low",
      tokensUsed: specTokens,
    };
  }

  // Step 4: Format results
  const { content, tokensUsed: formatTokens } = await formatResults(
    query,
    spec,
    data,
    validation.modelMeta
  );

  return {
    content,
    data,
    querySpec: spec,
    confidence: "high",
    tokensUsed: specTokens + formatTokens,
  };
}

